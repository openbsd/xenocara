/*
 * ZDI-CAN-33183: BufFileRawSkip negative skip out-of-bounds read
 *
 * A crafted PCF font has a table entry with offset 0xFFDFFFFF. When
 * pcfSeekToType() subtracts the current file position from this offset,
 * the result wraps to a negative value when truncated to the signed int
 * parameter of BufFileRawSkip(). The negative skip moves the buffer
 * pointer backward past the buffer start, causing subsequent
 * FontFileGetc() calls to read from invalid memory (heap OOB read or
 * SEGV).
 *
 * With the fix in bufio.c, BufFileRawSkip rejects negative count values
 * and returns BUFFILEEOF. Additionally, pcfSeekToType validates that the
 * skip distance fits in an int before calling FontFileSkip.
 *
 * Test font: test/data/negskip/evil-negskip.pcf
 * Generated by: test/gen_evil_pcf_negskip.py
 */

