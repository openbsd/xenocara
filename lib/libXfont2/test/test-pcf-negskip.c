#include "pcf-test-common.h"
#include <stdio.h>
#include <stdlib.h>

int
main(int argc, char **argv)
{
    xfont2_fpe_funcs_rec const **fpe_functions;
    int fpe_function_count;
    const char *builddir;
    char fontdir[512];

    builddir = getenv("builddir");
    if (!builddir)
        builddir = ".";

    fpe_functions = pcf_test_init(&fpe_function_count);

    snprintf(fontdir, sizeof(fontdir), "%s/test/data/negskip", builddir);
    return pcf_test_open_font(fpe_functions,
                              "ZDI-CAN-33183-negskip",
                              fontdir,
                              "-evil-negskip-medium-r-normal--10-100-75-75-c-80-iso10646-1");
}
