#include "pcf-test-common.h"
#include <stdio.h>
#include <stdlib.h>

int
main(int argc, char **argv)
{
    xfont2_fpe_funcs_rec const **fpe_functions;
    int fpe_function_count;
    const char *builddir;
    char fontdir[512];

    builddir = getenv("builddir");
    if (!builddir)
        builddir = ".";

    fpe_functions = pcf_test_init(&fpe_function_count);

    snprintf(fontdir, sizeof(fontdir), "%s/test/data/scale", builddir);
    /* Request pixel=16384 to inflate each glyph to ~62 MiB, causing the
     * total to exceed 256 MiB and trigger the size limit check.
     * Without the fix, the unsigned int accumulator wraps to ~1.5 MiB,
     * calloc succeeds, and ScaleBitmap overflows the buffer. */
    return pcf_test_open_font(fpe_functions,
                              "ZDI-CAN-30558-scale",
                              fontdir,
                              "-evil-scale-medium-r-normal--16384-0-75-75-c-0-iso10646-1");
}
