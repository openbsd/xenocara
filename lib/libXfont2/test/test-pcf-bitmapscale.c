/*
 * ZDI-CAN-30558: BitmapScaleBitmaps bytestoalloc integer overflow
 *
 * The font has 1105 small glyphs (1x2 pixels) stored at pixel=1. When
 * loaded at a larger pixel size, the bitmap scaler inflates each glyph.
 * With the old 'unsigned int' bytestoalloc, the accumulated size could
 * wrap past 2^32, causing calloc to allocate a tiny buffer while
 * ScaleBitmap writes the full (unwrapped) amount.
 *
 * With the fix in bitscale.c, bytestoalloc is size_t (no 32-bit wrap
 * on 64-bit platforms) and an explicit overflow check prevents wrap on
 * 32-bit platforms.
 *
 * Test font: test/data/scale/evil-scale.pcf
 * Generated by: test/gen_evil_pcf_bitmapscale.py
 */

