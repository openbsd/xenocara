#include "pcf-test-common.h"
#include <stdio.h>
#include <stdlib.h>

int
main(int argc, char **argv)
{
    xfont2_fpe_funcs_rec const **fpe_functions;
    int fpe_function_count;
    const char *builddir;
    char fontdir[512];

    builddir = getenv("builddir");
    if (!builddir)
        builddir = ".";

    fpe_functions = pcf_test_init(&fpe_function_count);

    snprintf(fontdir, sizeof(fontdir), "%s/test/data/props", builddir);
    return pcf_test_open_font(fpe_functions,
                              "ZDI-CAN-30560-props",
                              fontdir,
                              "-evil-props-medium-r-normal--20-200-75-75-c-80-iso10646-1");
}
