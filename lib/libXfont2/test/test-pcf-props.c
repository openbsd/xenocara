/*
 * ZDI-CAN-30560: computeProps property buffer heap overflow
 *
 * The font has 40 duplicate MIN_SPACE properties. When the bitmap
 * scaler processes this font, computeProps writes 2 slots per scaledX
 * match into the fixed 70-slot property buffer, overflowing after 25
 * matches (50 slots + 20 XLFD slots = 70, then overflow).
 *
 * With the fix in bitscale.c, computeProps checks remaining buffer
 * capacity and silently skips properties that would overflow.
 *
 * The font is stored at pixel=10; loading at pixel=20 triggers the
 * scaling path through ComputeScaledProperties -> computeProps.
 *
 * Test font: test/data/props/evil-props.pcf
 * Generated by: test/gen_evil_pcf_props.py
 */

